// Project progress ring with a filled pie for the completed share.
export function pie(f, cls = "") {
  const c = 8, r = 4.6;
  let wedge = "";
  if (f >= 0.999) wedge = `<circle cx="${c}" cy="${c}" r="${r}" fill="currentColor"/>`;
  else if (f > 0.001) {
    const a = 2 * Math.PI * f, x = c + r * Math.sin(a), y = c - r * Math.cos(a);
    wedge = `<path fill="currentColor" d="M${c},${c} L${c},${c - r} A${r},${r} 0 ${f > 0.5 ? 1 : 0} 1 ${x.toFixed(2)},${y.toFixed(2)} Z"/>`;
  }
  return `<svg class="pie ${cls}" viewBox="0 0 16 16" aria-hidden="true"><circle cx="${c}" cy="${c}" r="6.8" fill="none" stroke="currentColor" stroke-width="1.5"/>${wedge}</svg>`;
}
